def build_records(rows):
    return [{"field_values": row} for row in rows]

results = {}
for name, plan in PLANS.items():
    print(f"\n===== 创建 {name} =====")
    r = rpc("tencent-docs", "smartsheet.create_table_from_plan", {
        "file_id": FILE_ID, "properties": {}, "table_plan": plan
    })
    sheet_id = r.get("sheet_id") or r.get("tableId") or (r.get("result") or {}).get("sheet_id")
    print("  返回 keys:", list(r.keys()) if isinstance(r, dict) else type(r))
    if not sheet_id:
        print("  !! 未解析到 sheet_id，原始返回：", json.dumps(r, ensure_ascii=False)[:500])
        continue
    print("  sheet_id =", sheet_id)
    # 填记录
    rec = rpc("tencent-docs", "smartsheet.add_records", {
        "file_id": FILE_ID, "sheet_id": sheet_id, "records": build_records(RECORDS[name])
    })
    print("  add_records 返回：", json.dumps(rec, ensure_ascii=False)[:300])
    results[name] = sheet_id

print("\n===== 汇总 sheet_id =====")
print(json.dumps(results, ensure_ascii=False, indent=2))

